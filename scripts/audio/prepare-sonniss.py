"""Export selected AAC clips only. Originals are read-only; ffmpeg is an offline tool, not a runtime dependency."""
import argparse, array, concurrent.futures, hashlib, json, pathlib, subprocess, tempfile, wave
root = pathlib.Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser()
parser.add_argument('--source', type=pathlib.Path, default=root/'deletelater')
args = parser.parse_args()
selection = json.loads((root/'scripts/audio/sonniss-selection.json').read_text())
files = list(args.source.rglob('*.wav'))
out = root/'client/public/audio/sonniss-2026'
out.mkdir(parents=True, exist_ok=True)

def run(argv):
    return subprocess.run(argv, check=True, capture_output=True, text=True).stdout

def export(item):
    key, (name, maximum, category) = item
    matches = [f for f in files if f.name == name]
    if len(matches) != 1: raise ValueError(f'{name}: expected one exact match, found {len(matches)}')
    source = matches[0]
    before = hashlib.sha256(source.read_bytes()).hexdigest()
    with tempfile.TemporaryDirectory() as tmp:
        trimmed = pathlib.Path(tmp)/'trim.wav'
        run(['ffmpeg','-v','error','-i',str(source),'-af',f'silenceremove=start_periods=1:start_duration=0.005:start_threshold=-48dB,atrim=duration={maximum},asetpts=PTS-STARTPTS', '-ac','1','-ar','48000',str(trimmed)])
        duration = float(run(['ffprobe','-v','error','-show_entries','format=duration','-of','default=nw=1:nk=1',str(trimmed)]))
        if duration < 0.05: raise ValueError(f'{name}: no reliable audible section')
        loop = key in ('wind','portalHum','outdoor','lake')
        if loop:
            with wave.open(str(trimmed),'rb') as wav:
                rate=wav.getframerate(); samples=array.array('h',wav.readframes(wav.getnframes()))
            overlap=min(int(rate*.15),len(samples)//4)
            seam=array.array('h',(int(samples[-overlap+i]*(1-i/overlap)+samples[i]*(i/overlap)) for i in range(overlap)))
            joined=samples[overlap:-overlap]+seam
            with wave.open(str(trimmed),'wb') as wav:
                wav.setnchannels(1);wav.setsampwidth(2);wav.setframerate(rate);wav.writeframes(joined.tobytes())
            duration=len(joined)/rate
        fade = min(.18, duration/4)
        filters = f'loudnorm=I=-20:TP=-3:LRA=7,afade=t=in:d=0.006,afade=t=out:st={duration-fade}:d={fade}'
        if loop: filters='loudnorm=I=-23:TP=-3:LRA=7'
        target = out/f'{key}.m4a'
        run(['ffmpeg','-v','error','-y','-i',str(trimmed),'-af',filters,'-ac','1','-ar','48000','-c:a','aac','-b:a','80k','-movflags','+faststart',str(target)])
    assert hashlib.sha256(source.read_bytes()).hexdigest() == before, 'Original changed'
    return key, {'file':f'/audio/sonniss-2026/{key}.m4a','category':category,'duration':round(duration,3),'bytes':target.stat().st_size,'source':name,'sha256':before}
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
    manifest = dict(pool.map(export, selection.items()))
(root/'client/src/audio-clips.ts').write_text('// Generated by scripts/audio/prepare-sonniss.py. Selected, compressed assets only.\nexport const audioClips = '+json.dumps(manifest,indent=2)+' as const;\nexport type AudioClip = keyof typeof audioClips;\n')
print(f'{len(manifest)} clips, {sum(v["bytes"] for v in manifest.values()):,} bytes. Originals unchanged.')
